"""Build docs/data/population.js from NDC "Population Projections" Excel exports.

Usage (from repo root):
    pip install openpyxl
    python tools/convert_population.py

Inputs (downloaded from https://pop-proj.ndc.gov.tw/main_en/ -> Data Query):
    data/population/ndc_total_population.xlsx   (Total / Male / Female, medium variant)
    data/population/ndc_broad_age_group.xlsx    (0-14 / 15-64 / 65+, medium variant)
Only the LULC time steps are exported.
"""
import json
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "population"
YEARS = [1990, 2000, 2010, 2020, 2030, 2050]


def read(path):
    """Return (meta, {item: {year: persons}}) from an NDC Custom_SinglePopulation export."""
    rows = [r for r in openpyxl.load_workbook(path, data_only=True).active.iter_rows(values_only=True)]
    meta = {str(r[0]).rstrip("：:"): r[1] for r in rows if r[0] and r[1] and str(r[0]).endswith(("：", ":"))}
    yi = next(i for i, r in enumerate(rows) if r[0] is None and r[2] and str(r[2]).isdigit())
    years, kinds = rows[yi], rows[yi + 1]
    notes = [str(r[0]) for r in rows if r[0] and str(r[0]).startswith("●")]
    data = {}
    for r in rows[yi + 2:]:
        if r[0] != "Medium":
            continue
        data[r[1].strip()] = {int(y): int(v) for y, k, v in zip(years[2:], kinds[2:], r[2:])
                              if y and k and k.startswith("Data value")}
    return meta, data, notes


def main():
    m1, tot, notes = read(SRC / "ndc_total_population.xlsx")
    m2, age, _ = read(SRC / "ndc_broad_age_group.xlsx")
    first_proj = next(int(''.join(c for c in n if c.isdigit())[:4]) for n in notes if "projected" in n)
    for y in YEARS:  # internal consistency checks
        assert tot["Male"][y] + tot["Female"][y] == tot["Total"][y], y
        assert sum(age[g][y] for g in ("0-14", "15-64", "65 +")) == tot["Total"][y], y

    out = {
        "source": f"National Development Council (NDC), Population Projections for the R.O.C. (Taiwan), "
                  f"medium variant; data updated {m1['Update Date'].replace('.', '-')}",
        "projectedFrom": first_proj,
        "values": {y: tot["Total"][y] for y in YEARS},
        "sex": {y: {"male": tot["Male"][y], "female": tot["Female"][y]} for y in YEARS},
        "age": {y: {"0-14": age["0-14"][y], "15-64": age["15-64"][y], "65+": age["65 +"][y]} for y in YEARS},
        # Figures stated in the source paper (Liu & Arora). It gives no per-year values.
        "paper": {"growth_1990_2020_pct": 15.6, "total_millions": 23,
                  "trend_note": "Negative population growth since 2020"},
    }
    header = ("// Generated by tools/convert_population.py from NDC Excel exports in data/population/.\n"
              "// Values up to %d are recorded (household registration); later years are medium-variant projections.\n"
              % (first_proj - 1))
    (ROOT / "docs" / "data" / "population.js").write_text(
        header + "window.POPULATION = " + json.dumps(out, indent=1) + ";\n")
    for y in YEARS:
        print(y, out["values"][y], out["age"][y])


if __name__ == "__main__":
    main()
